-- Run in Supabase SQL Editor. Backend connects using a server-side database URL.
create table if not exists public.banks (
 ticker varchar(20) primary key, name text not null, institution_type text, ownership_type text,
 listing_status text, exchange text, official_url text,
 registry_status text not null default 'needs_verification', updated_at timestamptz default now()
);
create table if not exists public.observations (
 id bigint generated by default as identity primary key,
 ticker varchar(20) not null references public.banks(ticker), period varchar(20) not null,
 metric varchar(60) not null, value double precision, unit varchar(40),
 consolidation varchar(30) not null default 'consolidated', source_name text, source_url text,
 published_at varchar(40), retrieved_at timestamptz default now(),
 verification_status varchar(30) not null default 'unverified', note text,
 unique(ticker,period,metric,consolidation)
);
create index if not exists idx_observations_ticker_period on public.observations(ticker,period);
create index if not exists idx_observations_metric_period on public.observations(metric,period);
create table if not exists public.ingestion_runs (
 id bigint generated by default as identity primary key, source_name text not null,
 status varchar(30) not null, records_seen integer default 0, records_saved integer default 0,
 message text, started_at timestamptz default now(), finished_at timestamptz
);
create table if not exists public.source_registry (
 source_key varchar(50) primary key, display_name text not null, source_type varchar(40),
 enabled boolean default false, last_status varchar(30), last_checked_at timestamptz, notes text
);
