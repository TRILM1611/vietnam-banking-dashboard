ID_COL = "INTEGER PRIMARY KEY AUTOINCREMENT" if engine.dialect.name == "sqlite" else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
DDL = [
"""CREATE TABLE IF NOT EXISTS banks (ticker VARCHAR(20) PRIMARY KEY, name TEXT NOT NULL, institution_type TEXT, ownership_type TEXT, listing_status TEXT, exchange TEXT, official_url TEXT, registry_status TEXT NOT NULL DEFAULT 'needs_verification', updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""",
f"""CREATE TABLE IF NOT EXISTS observations (id {ID_COL}, ticker VARCHAR(20) NOT NULL, period VARCHAR(20) NOT NULL, metric VARCHAR(60) NOT NULL, value DOUBLE PRECISION, unit VARCHAR(40), consolidation VARCHAR(30) NOT NULL DEFAULT 'consolidated', source_name TEXT, source_url TEXT, published_at VARCHAR(40), retrieved_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, verification_status VARCHAR(30) NOT NULL DEFAULT 'unverified', note TEXT, UNIQUE(ticker, period, metric, consolidation))""",
f"""CREATE TABLE IF NOT EXISTS ingestion_runs (id {ID_COL}, source_name TEXT NOT NULL, status VARCHAR(30) NOT NULL, records_seen INTEGER DEFAULT 0, records_saved INTEGER DEFAULT 0, message TEXT, started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, finished_at TIMESTAMP)""",
"""CREATE TABLE IF NOT EXISTS source_registry (source_key VARCHAR(50) PRIMARY KEY, display_name TEXT NOT NULL, source_type VARCHAR(40), enabled BOOLEAN DEFAULT FALSE, last_status VARCHAR(30), last_checked_at TIMESTAMP, notes TEXT)""",
]

def init_db():
    with engine.begin() as c:
        for stmt in DDL: c.execute(text(stmt))
        # Explicitly mark connectors as not configured; never imply a live feed exists.
        for key, name, typ, note in [
            ("sbv", "Ngân hàng Nhà nước", "official", "Nguồn công bố chính thức; cần quy trình thu thập và kiểm tra từng chỉ tiêu."),
            ("bank_reports", "Báo cáo ngân hàng", "official", "Nhập BCTC/báo cáo thường niên, lưu URL và kỳ báo cáo."),
            ("ssi_market", "SSI FastConnect Data", "market_data", "Chỉ dữ liệu thị trường; cần SSI FastConnect V3 API Key/Secret và quyền sử dụng."),
            ("fundamental_vendor", "Nhà cung cấp dữ liệu cơ bản", "fundamentals", "Chưa cấu hình; cần hợp đồng/API key và quyền tái phân phối.")]:
            c.execute(text("INSERT INTO source_registry(source_key,display_name,source_type,enabled,notes) VALUES(:k,:n,:t,FALSE,:note) ON CONFLICT(source_key) DO NOTHING"), {"k":key,"n":name,"t":typ,"note":note})
